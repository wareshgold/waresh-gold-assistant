    getWelcomeMessage(
        firstName?: string,
        username?: string,
        returning?: boolean
    ): string {
        const messages = returning
            ? this.returningMessages
            : this.firstTimeMessages;

        const index = Math.floor(Math.random() * messages.length);
        const name = firstName ?? username ?? "دوست عزیز";

        return messages[index](name);
    }
